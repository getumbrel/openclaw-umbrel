function reconcileConfig() {
  const config = readConfig();
  if (!config) return;

  let changed = false;

  // Umbrel owns the gateway lifecycle and only proxies to the loopback listener.
  // Keep these explicit so upgrades or repaired configs cannot flip into a
  // gateway mode/bind that the wrapper does not manage.
  if (!config.gateway) config.gateway = {};
  if (config.gateway.mode !== "local") {
    config.gateway.mode = "local";
    changed = true;
    console.log("Patched config: set gateway mode to local");
  }
  if (config.gateway.bind !== "loopback") {
    config.gateway.bind = "loopback";
    changed = true;
    console.log("Patched config: set gateway bind to loopback");
  }
  if (config.gateway.port !== OPENCLAW_PORT) {
    config.gateway.port = OPENCLAW_PORT;
    changed = true;
    console.log(`Patched config: set gateway port to ${OPENCLAW_PORT}`);
  }

  // Umbrel authenticates the browser before it reaches this wrapper. Current
  // OpenClaw uses trusted-proxy identity for HTTP browsers without device keys.
  if (!config.gateway.controlUi) config.gateway.controlUi = {};
  for (const key of ["allowInsecureAuth", "dangerouslyDisableDeviceAuth"]) {
    if (key in config.gateway.controlUi) {
      delete config.gateway.controlUi[key];
      changed = true;
      console.log(`Patched config: removed retired ${key}`);
    }
  }
  const allowedOrigins = ensureArrayPath(config, ["gateway", "controlUi", "allowedOrigins"]);
  if (!allowedOrigins.includes(GATEWAY_ORIGIN)) {
    allowedOrigins.push(GATEWAY_ORIGIN);
    changed = true;
  }

  // Chromium's namespace sandbox is unavailable in the Umbrel container. The
  // browser still runs as the image's unprivileged `node` user and remains
  // inside the app container, but OpenClaw must pass --no-sandbox for it to
  // start reliably on Docker hosts.
  if (!config.browser || typeof config.browser !== "object" || Array.isArray(config.browser)) {
    config.browser = {};
  }
  if (config.browser.noSandbox !== true) {
    config.browser.noSandbox = true;
    changed = true;
    console.log("Patched config: enabled container-compatible browser mode");
  }

  // Disable update checks (updates are managed by Umbrel via Docker image bumps)
  if (!config.update) config.update = {};
  if (config.update.checkOnStart !== false) {
    config.update.checkOnStart = false;
    changed = true;
    console.log("Patched config: disabled update check on start");
  }

  // Enable Umbrel-managed context through OpenClaw's supported plugin surface.
  // The plugin also ships an `umbrel` skill, so one load path covers both the
  // always-on runtime context and deeper on-demand guidance.
  if (fs.existsSync(UMBREL_PLUGIN_PATH)) {
    if (!config.plugins || typeof config.plugins !== "object" || Array.isArray(config.plugins)) {
      config.plugins = {};
    }
    if (config.plugins.enabled !== true) {
      config.plugins.enabled = true;
      changed = true;
      console.log("Patched config: enabled plugins");
    }

    const pluginPaths = ensureArrayPath(config, ["plugins", "load", "paths"]);
    if (!pluginPaths.includes(UMBREL_PLUGIN_PATH)) {
      pluginPaths.push(UMBREL_PLUGIN_PATH);
      changed = true;
      console.log("Patched config: added Umbrel runtime plugin path");
    }

    if (Array.isArray(config.plugins.deny) && removeArrayItem(config.plugins.deny, UMBREL_PLUGIN_ID)) {
      changed = true;
      console.log("Patched config: removed Umbrel runtime plugin from deny list");
    }

    const allowedPlugins = config.plugins.allow;
    if (Array.isArray(allowedPlugins) && allowedPlugins.length > 0 && !allowedPlugins.includes(UMBREL_PLUGIN_ID)) {
      allowedPlugins.push(UMBREL_PLUGIN_ID);
      changed = true;
      console.log("Patched config: added Umbrel runtime plugin to allow list");
    }

    if (!config.plugins.entries || typeof config.plugins.entries !== "object" || Array.isArray(config.plugins.entries)) {
      config.plugins.entries = {};
    }
    const entry = config.plugins.entries[UMBREL_PLUGIN_ID] || {};
    if (entry.enabled !== true) {
      entry.enabled = true;
      config.plugins.entries[UMBREL_PLUGIN_ID] = entry;
      changed = true;
      console.log("Patched config: enabled Umbrel runtime plugin");
    }
    if (entry.hooks?.allowConversationAccess !== true) {
      entry.hooks = { ...entry.hooks, allowConversationAccess: true };
      config.plugins.entries[UMBREL_PLUGIN_ID] = entry;
      changed = true;
      console.log("Patched config: allowed Umbrel runtime prompt hook");
    }
  } else {
    console.warn(`Umbrel context: ${UMBREL_PLUGIN_PATH} not found; plugin config will be reconciled on next startup`);
  }

  // The Gateway trusts only loopback ingress for the Umbrel owner. Device enrollment
  // grants ordinary UI scopes; admin access belongs to the verified proxy
  // identity on each connection, not to a durable unrestricted device token.
  if (!config.gateway.auth) config.gateway.auth = {};
  const trustedProxy = {
    userHeader: UMBREL_USER_HEADER,
    allowUsers: [UMBREL_OWNER],
    allowLoopback: true,
    requiredHeaders: ["x-forwarded-for"],
    deviceAutoApprove: {
      enabled: true,
      scopes: ["operator.read", "operator.write", "operator.approvals", "operator.questions"],
    },
  };
  for (const [key, value] of Object.entries({
    mode: "trusted-proxy",
    trustedProxy,
    identityScopes: { [UMBREL_OWNER]: ["operator.admin"] },
  })) {
    if (JSON.stringify(config.gateway.auth[key]) !== JSON.stringify(value)) {
      config.gateway.auth[key] = value;
      changed = true;
    }
  }
  if (JSON.stringify(config.gateway.trustedProxies) !== JSON.stringify(["127.0.0.1/32"])) {
    config.gateway.trustedProxies = ["127.0.0.1/32"];
    changed = true;
  }
  if ("token" in config.gateway.auth) {
    delete config.gateway.auth.token;
    changed = true;
  }

  // Direct internal CLI/RPC clients use a password without passing through the
  // browser proxy. Preserve supported password SecretRefs across restarts.
  const env = readEnv();
  let password = resolveGatewaySecretValue(config.gateway.auth.password, env);
  if (!password) {
    config.gateway.auth.password = crypto.randomBytes(24).toString("hex");
    password = config.gateway.auth.password;
    changed = true;
    console.log("Patched config: generated internal gateway password");
  } else if (config.gateway.auth.password?.source === "env" &&
             config.gateway.auth.password.id === "OPENCLAW_GATEWAY_TOKEN") {
    // This variable must be removed for trusted-proxy mode; retain its resolved
    // password value rather than leaving a reference to a deleted credential.
    config.gateway.auth.password = password;
    changed = true;
  }
  if (changed) {
    writeConfig(config);
  }

  const previousEnv = JSON.stringify(env);
  delete env.OPENCLAW_GATEWAY_TOKEN;
  if (config.gateway.auth.password?.source === "env" &&
      config.gateway.auth.password.id !== "OPENCLAW_GATEWAY_PASSWORD") {
    delete env.OPENCLAW_GATEWAY_PASSWORD;
  } else {
    env.OPENCLAW_GATEWAY_PASSWORD = password;
  }
  if (JSON.stringify(env) !== previousEnv) {
    writeEnv(env);
    console.log("Synced internal gateway credentials to .env");
  }
}

// Recovery-only repair path. OpenClaw's container gateway already runs its own
// per-version startup migrations and plugin convergence before reporting ready,
// so running Doctor on every ordinary restart is redundant and slow.
async function runDoctor() {
  try {
    await execFileAsync("openclaw", ["doctor", "--repair", "--yes", "--non-interactive"], {
      env: getOpenClawEnv(),
      timeout: MAINTENANCE_TIMEOUT_MS,
      maxBuffer: 4 * 1024 * 1024,
    });
    console.log("openclaw doctor completed");
    return true;
  } catch (e) {
    console.error("openclaw doctor failed:", e.message);
    return false;
  }
}

// Doctor can persist only its currently activated plugin subset. When recovery
// actually invokes Doctor, rebuild the complete registry afterward so bundled
// command/tool plugins such as browser remain available.
async function refreshPluginRegistry() {
  try {
    await execFileAsync(
      "openclaw",
      ["plugins", "registry", "--refresh", "--json"],
      {
        env: getOpenClawEnv(),
        timeout: MAINTENANCE_TIMEOUT_MS,
        maxBuffer: 4 * 1024 * 1024,
      }
    );
    console.log("OpenClaw plugin registry refreshed");
    return true;
  } catch (e) {
    console.error("OpenClaw plugin registry refresh failed:", e.message);
    return false;
  }
}

async function prepareOpenclaw({ repair }) {
  reconcileConfig();
  if (!repair) return;

  console.log("Running one automatic OpenClaw startup repair...");
  await runDoctor();
  // Doctor may migrate or rewrite configuration, so re-assert the small set
  // of settings owned by the Umbrel wrapper before rebuilding the registry.
  reconcileConfig();
  await refreshPluginRegistry();
}

function getConfigFingerprint() {
  try {
    return crypto.createHash("sha256").update(fs.readFileSync(CONFIG_FILE)).digest("hex");
  } catch {
    return "missing";
  }
}

function clearResolvedConfigFailure() {
  if (
    gatewayFailure?.code === GATEWAY_CONFIG_EXIT_CODE &&
    gatewayFailure.repairing !== true &&
    gatewayFailure.configFingerprint !== getConfigFingerprint()
  ) {
    console.log("OpenClaw config changed; clearing exit-78 restart block");
    gatewayFailure = null;
    gatewayRepairAttempted = false;
    gatewayRestartAttempts = 0;
    gatewayNextStartAt = 0;
  }
}

function computeRestartDelay() {
  const exponent = Math.max(0, gatewayRestartAttempts - 1);
  return Math.min(2_000 * (2 ** exponent), GATEWAY_MAX_RESTART_DELAY_MS);
}

function scheduleGatewayRestart(delayMs) {
  if (shuttingDown || gatewayRestartTimer || gatewayFailure?.code === GATEWAY_CONFIG_EXIT_CODE) {
    return;
  }
  gatewayNextStartAt = Date.now() + delayMs;
  console.log(`Scheduling OpenClaw gateway restart in ${delayMs}ms`);
  gatewayRestartTimer = setTimeout(() => {
    gatewayRestartTimer = null;
    gatewayNextStartAt = 0;
    startOpenclaw();
  }, delayMs);
}

function recordGatewayExit(code, signal) {
  const runDuration = gatewayStartedAt ? Date.now() - gatewayStartedAt : 0;
  gatewayStartedAt = 0;

  if (shuttingDown) return;

  // OpenClaw uses exit 78 for invalid config, but its startup migration guard
  // currently reports some repairable convergence failures as an early exit 1.
  // Repair either case once per wrapper lifetime; healthy boots pay no cost.
  const repairableStartupFailure =
    code === GATEWAY_CONFIG_EXIT_CODE ||
    (code === 1 && runDuration < GATEWAY_STABLE_RUN_MS);
  if (repairableStartupFailure && !gatewayRepairAttempted) {
    gatewayRepairAttempted = true;
    gatewayFailure = {
      code,
      signal,
      repairing: true,
      configFingerprint: getConfigFingerprint(),
      at: Date.now(),
    };
    gatewayNextStartAt = Number.POSITIVE_INFINITY;
    openclawStarting = true;
    console.error(
      `OpenClaw stopped with exit ${code} during startup; attempting one automatic repair`
    );
    prepareOpenclaw({ repair: true })
      .catch((err) => {
        console.error("OpenClaw automatic repair failed:", err.message);
      })
      .finally(() => {
        openclawStarting = false;
        if (shuttingDown) return;
        gatewayFailure = null;
        gatewayNextStartAt = 0;
        console.log("Retrying OpenClaw gateway after automatic repair...");
        startOpenclaw();
      });
    return;
  }

  if (code === GATEWAY_CONFIG_EXIT_CODE) {
    gatewayFailure = {
      code,
      signal,
      configFingerprint: getConfigFingerprint(),
      at: Date.now(),
    };
    gatewayNextStartAt = Number.POSITIVE_INFINITY;
    console.error(
      "OpenClaw stopped with exit 78; automatic restarts are blocked until the config changes or the app restarts"
    );
    return;
  }

  const failedBySignal = Boolean(
    signal && !["SIGINT", "SIGTERM"].includes(signal)
  );
  if ((code !== null && code !== 0) || failedBySignal) {
    gatewayRestartAttempts = runDuration >= GATEWAY_STABLE_RUN_MS
      ? 1
      : gatewayRestartAttempts + 1;
    gatewayFailure = { code, signal, at: Date.now() };
    scheduleGatewayRestart(computeRestartDelay());
    return;
  }

  // Clean exits and signal-driven restarts (including the systemctl shim) are
  // intentional. Relaunch promptly so channel delivery does not depend on an
  // open dashboard tab making the next HTTP request.
  gatewayRestartAttempts = 0;
  gatewayFailure = null;
  scheduleGatewayRestart(250);
}

function spawnGateway() {
  openclawStarting = false;
  gatewayNextStartAt = 0;
  gatewayFailure = null;
  console.log("Starting OpenClaw gateway...");
  const child = spawn(
    "openclaw",
    ["gateway", "--port", OPENCLAW_PORT.toString()],
    {
      stdio: "inherit",
      env: getOpenClawEnv(),
    }
  );
  openclawProcess = child;

  child.once("spawn", () => {
    gatewayStartedAt = Date.now();
  });

  child.once("error", (err) => {
    if (openclawProcess !== child) return;
    console.error("Failed to start OpenClaw gateway:", err.message);
    openclawProcess = null;
    openclawStarting = false;
    gatewayRestartAttempts += 1;
    gatewayFailure = { code: null, signal: null, at: Date.now(), message: err.message };
    scheduleGatewayRestart(computeRestartDelay());
  });

  child.once("exit", (code, signal) => {
    if (openclawProcess !== child) return;
    console.log(`OpenClaw exited with code ${code}${signal ? ` (${signal})` : ""}`);
    openclawProcess = null;
    openclawStarting = false;
    recordGatewayExit(code, signal);
  });
}

function startOpenclaw() {
  clearResolvedConfigFailure();

  // Guard against async reconciliation/recovery and duplicate request/restart triggers.
  if (
    shuttingDown ||
    openclawProcess ||
    openclawStarting ||
    gatewayFailure?.code === GATEWAY_CONFIG_EXIT_CODE ||
    Date.now() < gatewayNextStartAt
  ) {
    return false;
  }

  openclawStarting = true;
  prepareOpenclaw({ repair: false })
    .then(spawnGateway)
    .catch((err) => {
      openclawStarting = false;
      console.error("OpenClaw startup preparation failed:", err.message);
      gatewayRestartAttempts += 1;
      gatewayFailure = { code: null, signal: null, at: Date.now(), message: err.message };
      scheduleGatewayRestart(computeRestartDelay());
    });
  return true;
}

