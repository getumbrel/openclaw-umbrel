function getOpenClawEnv() {
  const env = {
    ...process.env,
    ...readEnv(),
    OPENCLAW_STATE_DIR: CONFIG_DIR,
    OPENCLAW_SERVICE_REPAIR_POLICY: "external",
    OPENCLAW_SUPERVISOR_MODE: "external",
    OPENCLAW_NO_RESPAWN: "1",
  };
  // Trusted-proxy mode rejects a shared token, including inherited overrides.
  delete env.OPENCLAW_GATEWAY_TOKEN;
  const password = resolveGatewaySecretValue(readConfig()?.gateway?.auth?.password, env);
  if (password) env.OPENCLAW_GATEWAY_PASSWORD = password;
  return env;
}

function readEnv() {
  const env = {};
  try {
    if (fs.existsSync(ENV_FILE)) {
      const content = fs.readFileSync(ENV_FILE, "utf8");
      content.split("\n").forEach((line) => {
        const match = line.match(/^([A-Z_][A-Z0-9_]*)=(.*)$/);
        if (match) {
          env[match[1]] = match[2];
        }
      });
    }
  } catch (e) {
    console.error("Error reading env:", e);
  }
  return env;
}

function writeEnv(env) {
  const lines = ["# OpenClaw Configuration", "# Generated by setup wizard", ""];
  for (const [key, value] of Object.entries(env)) {
    if (value) {
      lines.push(`${key}=${value}`);
    }
  }
  fs.writeFileSync(ENV_FILE, lines.join("\n") + "\n", { mode: 0o600 });
}

function writeConfig(config) {
  fs.writeFileSync(CONFIG_FILE, JSON.stringify(config, null, 2), { mode: 0o600 });
}

function ensureConfigDir() {
  if (!fs.existsSync(CONFIG_DIR)) {
    fs.mkdirSync(CONFIG_DIR, { recursive: true });
  }
  const workspaceDir = path.join(CONFIG_DIR, "workspace");
  if (!fs.existsSync(workspaceDir)) {
    fs.mkdirSync(workspaceDir, { recursive: true });
  }
}

function ensureShellCompletionBypass() {
  const completionDir = path.join(CONFIG_DIR, "completions");
  const completionPath = path.join(completionDir, "openclaw.bash");
  const bashrcPath = path.join(process.env.HOME, ".bashrc");

  fs.mkdirSync(completionDir, { recursive: true });
  if (!fs.existsSync(completionPath)) {
    fs.writeFileSync(completionPath, "# OpenClaw tab-completion disabled in Umbrel.\n");
  }

  let bashrc = "";
  try {
    bashrc = fs.readFileSync(bashrcPath, "utf8");
  } catch {}

  if (!bashrc.includes("# OpenClaw Completion")) {
    // OpenClaw QuickStart auto-generates shell tab-completion when it looks
    // unconfigured. That is not useful in Umbrel's browser terminal and can
    // take ~30s. The marker plus placeholder cache makes OpenClaw skip that
    // setup step without sourcing or executing anything on shell startup.
    const prefix = bashrc && !bashrc.endsWith("\n") ? "\n" : "";
    fs.appendFileSync(bashrcPath, `${prefix}\n# OpenClaw Completion\n`);
  }
}

// Check if a directory is empty
async function isDirEmpty(dirPath) {
  try {
    const entries = await fsp.readdir(dirPath);
    return entries.length === 0;
  } catch {
    return true; // If we can't read it, treat as empty
  }
}

// Copy files from /home-skeleton to $HOME if they don't exist or are empty.
// Never seed .openclaw from the image: npm lifecycle scripts can create a
// build-time plugin registry there, but runtime state must be derived from the
// installed version and the user's persisted configuration.
async function initializeHome() {
  const homeDir = process.env.HOME;

  try {
    const entries = await fsp.readdir(SKELETON_DIR, { withFileTypes: true });

    for (const entry of entries) {
      if (entry.name === ".openclaw") {
        console.log("Skipping image-generated .openclaw state");
        continue;
      }

      const srcPath = path.join(SKELETON_DIR, entry.name);
      const destPath = path.join(homeDir, entry.name);

      try {
        await fsp.access(destPath);
        // Exists - check if it's an empty directory
        if (entry.isDirectory() && (await isDirEmpty(destPath))) {
          console.log(
            `${entry.name} exists but is empty, copying contents inside...`
          );
          const children = await fsp.readdir(srcPath);
          for (const child of children) {
            await fsp.cp(path.join(srcPath, child), path.join(destPath, child), {
              recursive: true,
              force: false,
              errorOnExist: false,
            });
          }
        } else {
          console.log(`Skipping ${entry.name} (already exists)`);
        }
      } catch {
        // Doesn't exist, copy it
        console.log(`Copying ${entry.name} to home...`);
        if (entry.isDirectory()) {
          await fsp.cp(srcPath, destPath, {
            recursive: true,
            force: false,
            errorOnExist: false,
          });
        } else {
          await fsp.copyFile(srcPath, destPath);
        }
      }
    }
    console.log("Home directory initialized");
  } catch (err) {
    console.error("Error initializing home:", err.message);
  }
}

// Config corruption recovery:
// - Mid-run: the gateway keeps its in-memory config and stays up — no action needed.
// - On restart: the gateway tries to boot from the corrupt file and refuses to start.
//   We have two layers of defense:
//   1. readConfig() restores from OpenClaw's native .bak file (covers parse failures).
//   2. One bounded Doctor repair runs after OpenClaw reports a startup/config
//      failure (catches migration issues or structural problems that valid JSON
//      + .bak can't fix without slowing every healthy start).
// - If both .json and .bak are gone/corrupt, readConfig() returns null. isConfigured()
//   falls through to checking the durable .env for API keys. OpenClaw's other auth
//   stores remain untouched, but without a readable config the wrapper cannot infer
//   that onboarding completed and safely returns to setup.
function readConfig() {
  try {
    if (fs.existsSync(CONFIG_FILE)) {
      return JSON.parse(fs.readFileSync(CONFIG_FILE, "utf8"));
    }
  } catch (e) {
    console.error("Config file corrupted, attempting restore from backup...");
    const backupFile = CONFIG_FILE + ".bak";
    try {
      if (fs.existsSync(backupFile)) {
        fs.copyFileSync(backupFile, CONFIG_FILE);
        console.log("Restored config from backup");
        return JSON.parse(fs.readFileSync(CONFIG_FILE, "utf8"));
      }
    } catch (e2) {
      console.error("Backup restore also failed:", e2.message);
    }
  }
  return null;
}

function ensureArrayPath(root, keys) {
  let current = root;
  for (const key of keys.slice(0, -1)) {
    if (!current[key] || typeof current[key] !== "object" || Array.isArray(current[key])) {
      current[key] = {};
    }
    current = current[key];
  }

  const leaf = keys[keys.length - 1];
  if (!Array.isArray(current[leaf])) {
    current[leaf] = [];
  }
  return current[leaf];
}

function removeArrayItem(items, item) {
  let changed = false;
  for (let i = items.length - 1; i >= 0; i -= 1) {
    if (items[i] === item) {
      items.splice(i, 1);
      changed = true;
    }
  }
  return changed;
}

function resolveGatewaySecretValue(value, env = readEnv()) {
  if (typeof value === "string" && value.length > 0) {
    return value;
  }

  // OpenClaw's supported onboarding SecretRef form. Resolving the common env
  // source here keeps internal CLI clients on the Gateway's password.
  if (
    value &&
    typeof value === "object" &&
    !Array.isArray(value) &&
    value.source === "env" &&
    typeof value.id === "string" &&
    value.id.length > 0
  ) {
    return env[value.id] || process.env[value.id] || null;
  }

  return null;
}

