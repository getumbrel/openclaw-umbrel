function isAllowedBrowserRequest(req) {
  // The proxy now supplies browser identity, so reject cross-origin requests
  // before rewriting Origin. Umbrel preserves Host and supplies the original
  // protocol when terminating TLS. Do not accept an HTTP origin on an HTTPS app.
  const origin = req.headers.origin;
  if (origin === undefined) {
    return req.headers["sec-fetch-site"] !== "cross-site" ||
      (req.method === "GET" && req.headers["sec-fetch-mode"] === "navigate");
  }
  try {
    const parsed = new URL(origin);
    const protocol = req.headers["x-forwarded-proto"] || (req.socket.encrypted ? "https" : "http");
    if (!["http", "https"].includes(protocol)) return false;
    const expected = new URL(`${protocol}://${req.headers.host}`);
    return ["http:", "https:"].includes(parsed.protocol) &&
      !parsed.username && !parsed.password && !parsed.search && !parsed.hash &&
      parsed.pathname === "/" && !expected.username && !expected.password &&
      parsed.origin === expected.origin;
  } catch {
    return false;
  }
}

function getGatewayProxyHeaders(req) {
  if (!isAllowedBrowserRequest(req)) return null;
  // Attribute this hop to the actual Umbrel proxy socket, never a caller's XFF.
  // OpenClaw requires a non-loopback forwarded peer. Direct in-container CLI
  // clients should use the Gateway's password on port 18790 instead.
  const peer = req.socket.remoteAddress?.replace(/^::ffff:/i, "");
  if (!net.isIP(peer || "") || peer === "::1" || peer === "::" ||
      peer === "0.0.0.0" || /^127\./.test(peer)) {
    return null;
  }
  const headers = {};
  for (const [name, value] of Object.entries(req.headers)) {
    const key = name.toLowerCase();
    if (key.startsWith("x-forwarded-") || key.startsWith("tailscale-") ||
        ["forwarded", "x-real-ip", UMBREL_USER_HEADER, "authorization", "proxy-authorization"].includes(key)) {
      continue;
    }
    headers[key] = value;
  }
  headers.host = GATEWAY_HOST;
  if (headers.origin) headers.origin = GATEWAY_ORIGIN;
  headers["x-forwarded-for"] = peer;
  headers[UMBREL_USER_HEADER] = UMBREL_OWNER;
  return headers;
}

function renderGatewayUnavailable(res) {
  const configBlocked =
    gatewayFailure?.code === GATEWAY_CONFIG_EXIT_CODE &&
    gatewayFailure.repairing !== true;
  res.writeHead(configBlocked ? 503 : 200, {
    "Content-Type": "text/html",
    "Cache-Control": "no-store",
    "Referrer-Policy": "no-referrer",
  });
  res.end(configBlocked ? CONFIG_ERROR_HTML : LOADING_HTML);
}

function proxyToOpenclaw(req, res) {
  const headers = getGatewayProxyHeaders(req);
  if (!headers) {
    res.writeHead(403, { "Content-Type": "text/plain" });
    res.end("Forbidden");
    return;
  }

  const options = {
    hostname: "127.0.0.1",
    port: OPENCLAW_PORT,
    path: req.url,
    method: req.method,
    headers: headers,
  };

  const proxy = http.request(options, (proxyRes) => {
    res.writeHead(proxyRes.statusCode, proxyRes.headers);
    proxyRes.pipe(res);
  });

  proxy.on("error", () => {
    renderGatewayUnavailable(res);
  });

  req.pipe(proxy);
}

// Handle WebSocket upgrade requests
function handleUpgrade(req, socket, head) {
  const headers = getGatewayProxyHeaders(req);
  if (!headers) {
    socket.end("HTTP/1.1 403 Forbidden\r\nConnection: close\r\n\r\n");
    return;
  }

  // Connect to OpenClaw gateway
  const proxySocket = net.connect(OPENCLAW_PORT, "127.0.0.1", () => {
    // Rebuild the upgrade request with the same identity policy as HTTP.
    let requestLine = `${req.method} ${req.url} HTTP/1.1\r\n`;

    let headerLines = "";
    for (const [key, value] of Object.entries(headers)) {
      if (Array.isArray(value)) {
        value.forEach((v) => (headerLines += `${key}: ${v}\r\n`));
      } else {
        headerLines += `${key}: ${value}\r\n`;
      }
    }

    // Send the upgrade request to OpenClaw
    proxySocket.write(requestLine + headerLines + "\r\n");
    if (head && head.length) {
      proxySocket.write(head);
    }

    // Pipe data between client and OpenClaw
    socket.pipe(proxySocket);
    proxySocket.pipe(socket);
  });

  proxySocket.on("error", (err) => {
    console.error("WebSocket proxy error:", err.message);
    socket.end();
  });

  socket.on("error", (err) => {
    console.error("Client socket error:", err.message);
    proxySocket.end();
  });

  socket.on("close", () => {
    proxySocket.end();
  });

  proxySocket.on("close", () => {
    socket.end();
  });
}

const server = http.createServer((req, res) => {
  if (!isAllowedBrowserRequest(req)) {
    res.writeHead(403, { "Content-Type": "text/plain" });
    res.end("Forbidden");
    return;
  }
  // Serve static assets for setup UI
  if (req.url === "/logo.webp") {
    res.writeHead(200, { "Content-Type": "image/webp", "Cache-Control": "public, max-age=86400" });
    res.end(LOGO);
    return;
  }

  if (!isConfigured()) {
    if (req.url !== "/") {
      res.writeHead(302, { Location: "/" });
      res.end();
      return;
    }
    res.writeHead(200, { "Content-Type": "text/html" });
    res.end(SETUP_HTML.replace("__SETUP_TOKEN__", SETUP_TOKEN));
    return;
  }

  if (ptyProcess) {
    // OpenClaw writes config before QuickStart fully exits. Keep the browser on
    // the terminal until onboarding is done so the gateway never starts against
    // config/auth files that OpenClaw may still rewrite.
    if (req.url !== "/") {
      res.writeHead(302, { Location: "/" });
      res.end();
      return;
    }
    res.writeHead(200, { "Content-Type": "text/html" });
    res.end(SETUP_HTML.replace("__SETUP_TOKEN__", SETUP_TOKEN));
    return;
  }

  // If configured but OpenClaw not running, start it
  if (!openclawProcess) {
    startOpenclaw();
  }

  // Proxy to OpenClaw
  proxyToOpenclaw(req, res);
});

// WebSocket server for the interactive terminal
const wss = new WebSocket.Server({ noServer: true });

wss.on("connection", (ws) => {
  console.log("Terminal WebSocket connected");

  // Only one setup session at a time — kill any existing PTY (e.g. stale tab).
  // Each handler below keeps its own setupPty reference so a delayed close from
  // an old browser session cannot accidentally kill the newly active session.
  if (ptyProcess) {
    try { ptyProcess.kill(); } catch (e) {}
    ptyProcess = null;
  }

  // Keep the classic terminal setup, including telemetry consent and agent naming.
  // reconcileConfig() normalizes the internal gateway port and auth afterward;
  // this also covers interactive OpenClaw versions that ignore --gateway-port.
  ensureConfigDir();
  ensureShellCompletionBypass();
  const setupPty = pty.spawn("openclaw", [
    "onboard",
    "--classic",
    "--flow", "quickstart",
    "--accept-risk",
    "--skip-channels",
    "--skip-skills",
    "--skip-search",
    "--skip-daemon",
    "--skip-ui",
    "--skip-health",
    "--skip-hooks",
    "--skip-bootstrap",
    "--mode", "local",
    "--gateway-port", OPENCLAW_PORT.toString(),
    "--gateway-bind", "loopback",
  ], {
    name: "xterm-256color",
    cols: 80,
    rows: 24,
    cwd: CONFIG_DIR,
    env: {
      ...getOpenClawEnv(),
      SHELL: "/bin/bash",
      TERM: "xterm-256color",
    },
  });
  ptyProcess = setupPty;

  // PTY output -> WebSocket
  setupPty.onData((data) => {
    try {
      if (ws.readyState === WebSocket.OPEN) {
        ws.send(JSON.stringify({ type: "output", data }));
      }
    } catch (e) {
      console.error("Error sending PTY output:", e.message);
    }
  });

  // PTY exit -> notify client
  setupPty.onExit(({ exitCode }) => {
    console.log(`openclaw onboard exited with code ${exitCode}`);
    const wasActiveSession = ptyProcess === setupPty;
    try {
      if (ws.readyState === WebSocket.OPEN) {
        ws.send(JSON.stringify({ type: "exit", code: exitCode }));
      }
    } catch (e) {
      console.error("Error sending exit message:", e.message);
    }
    if (wasActiveSession) {
      ptyProcess = null;
    }

    if (wasActiveSession && exitCode === 0 && isConfigured() && !openclawProcess) {
      console.log("OpenClaw onboarding completed, starting gateway...");
      startOpenclaw();
    }
  });

  // WebSocket input -> PTY
  ws.on("message", (msg) => {
    try {
      const parsed = JSON.parse(msg);
      if (ptyProcess !== setupPty) {
        return;
      }
      if (parsed.type === "input") {
        setupPty.write(parsed.data);
      } else if (parsed.type === "resize") {
        setupPty.resize(parsed.cols, parsed.rows);
      }
    } catch (e) {
      console.error("Error processing terminal input:", e.message);
    }
  });

  ws.on("close", () => {
    console.log("Terminal WebSocket closed");
    if (ptyProcess === setupPty) {
      try { setupPty.kill(); } catch (e) {}
      ptyProcess = null;
    }
  });
});

// Handle WebSocket upgrades
server.on("upgrade", (req, socket, head) => {
  if (!isAllowedBrowserRequest(req)) {
    socket.end("HTTP/1.1 403 Forbidden\r\nConnection: close\r\n\r\n");
    return;
  }
  const url = new URL(req.url, `http://${req.headers.host}`);

  // Route /api/terminal to the PTY WebSocket server
  if (url.pathname === "/api/terminal") {
    // Validate anti-CSWSH token (see SETUP_TOKEN comment above)
    const provided = url.searchParams.get("token") || "";
    if (!SETUP_TOKEN || provided.length !== SETUP_TOKEN.length ||
        !crypto.timingSafeEqual(Buffer.from(provided), Buffer.from(SETUP_TOKEN))) {
      socket.write("HTTP/1.1 403 Forbidden\r\n\r\n");
      socket.destroy();
      return;
    }
    wss.handleUpgrade(req, socket, head, (ws) => {
      wss.emit("connection", ws, req);
    });
    return;
  }

  if (!isConfigured()) {
    socket.end("HTTP/1.1 503 Service Unavailable\r\n\r\n");
    return;
  }

  if (ptyProcess) {
    socket.end("HTTP/1.1 503 Service Unavailable\r\n\r\n");
    return;
  }

  if (!openclawProcess) {
    startOpenclaw();
  }

  handleUpgrade(req, socket, head);
});

async function main() {
  // Finish persistent-home initialization before creating OpenClaw's state
  // directory. This removes the former startup race that could skip skeleton
  // content depending on filesystem timing.
  await initializeHome();
  ensureConfigDir();

  if (isConfigured()) {
    console.log("OpenClaw is configured, starting gateway...");
    startOpenclaw();
  } else {
    console.log("OpenClaw not configured, showing setup UI...");
  }

  server.listen(PORT, "0.0.0.0", () => {
    console.log(`Setup server listening on port ${PORT}`);
  });
}

// Graceful shutdown: Docker sends SIGTERM on stop/restart/update.
// Without this, child processes (gateway, PTY) may get hard-killed
// mid-write and corrupt config or state files.
function shutdown() {
  console.log("Received SIGTERM, shutting down...");
  shuttingDown = true;
  if (gatewayRestartTimer) {
    clearTimeout(gatewayRestartTimer);
    gatewayRestartTimer = null;
  }
  if (ptyProcess) {
    try { ptyProcess.kill(); } catch (e) {}
  }
  if (openclawProcess) {
    openclawProcess.kill("SIGTERM");
  }
  server.close();
}

if (require.main === module) {
  main().catch((err) => {
    console.error("Failed to initialize OpenClaw wrapper:", err);
    process.exitCode = 1;
  });
  process.on("SIGTERM", shutdown);
}

